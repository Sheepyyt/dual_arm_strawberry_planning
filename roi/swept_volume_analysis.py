def _draw_boundary_panel(ax, info, boundary_x):
    """Draw a single boundary‑search panel."""
    # Support both old (left/right) and new (fixed/moving) key names
    left_pts = info.get("left_link_pts", info.get("fixed_link_pts", np.empty((0, 2))))
    right_pts = info.get("right_link_pts", info.get("moving_link_pts", np.empty((0, 2))))

    if len(left_pts) >= 3:
        _draw_hull(ax, left_pts, "#6A8EC4", "Fixed arm body", alpha=0.25)
        ax.scatter(left_pts[:, 0], left_pts[:, 1], s=1, c="#AFC4E4", alpha=0.2)

    if len(right_pts) >= 3:
        _draw_hull(ax, right_pts, "#5CA86C", "Moving arm body", alpha=0.25)
        ax.scatter(right_pts[:, 0], right_pts[:, 1], s=1, c="#BEE4C8", alpha=0.2)

    if boundary_x is not None:
        ax.axvline(boundary_x, color="red", linewidth=2, linestyle="-",
                   label=f"Boundary x={boundary_x:.3f}", zorder=6)
        # Force y limits before shading
        ax.set_ylim(-0.85, 0.85)
        y_lo, y_hi = ax.get_ylim()
        ax.fill_betweenx([y_lo, y_hi], PLOT_CONFIG["body_x_min"] - 0.5, boundary_x,
                         color="#AFC4E4", alpha=0.05, zorder=0)
        ax.fill_betweenx([y_lo, y_hi], boundary_x, PLOT_CONFIG["body_x_max"] + 0.5,
                         color="#BEE4C8", alpha=0.05, zorder=0)

    overlap_flag = info.get("overlap", True)
    status = "✗ OVERLAP" if overlap_flag else "✓ SAFE"
    ax.set_title(ax.get_title() + f"  [{status}]", fontsize=9)
    ax.legend(loc="upper left", fontsize=6)



        f" ScB raw:    {_fmt(bnd_B_raw, info_B_raw)}",
        f" ScB buf:    {_fmt(bnd_B_buf, info_B_buf)}",
        "",
        "─── Lower (B4/B5/B6) ───",
        f" ScA raw:    {_fmt(bnd_A_raw_lo, info_A_raw_lo)}",
        f" ScA buf:    {_fmt(bnd_A_buf_lo, info_A_buf_lo)}",
        f" ScB raw:    {_fmt(bnd_B_raw_lo, info_B_raw_lo)}",

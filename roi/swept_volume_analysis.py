def plot_per_region_swept_volumes(swept, ee_points, T_left, T_right):
    """
    Produce a figure with one subplot per planning region, showing both
    arms' link swept volumes within that region.
    """
    regions_to_plot = ["B1", "B2", "B3", "B4", "B5", "B6"]
    fig, axes = plt.subplots(2, 3, figsize=(21, 14))
    fig.suptitle("Per‑Region Link Swept Volumes (XY projection)", fontsize=13)

    for idx, reg_name in enumerate(regions_to_plot):
        ax = axes[idx // 3][idx % 3]
        _setup_ax(ax, f"Region {reg_name}", T_left, T_right)

        for arm, color_scatter, color_hull, label in [
            ("left",  "#AFC4E4", "#6A8EC4", "L links"),
            ("right", "#BEE4C8", "#5CA86C", "R links"),
        ]:
            pts = swept[arm].get(reg_name, np.empty((0, 3)))
            if len(pts) > 0:
                xy = pts[:, :2]
                ax.scatter(xy[:, 0], xy[:, 1], s=2, c=color_scatter, alpha=0.4)
                _draw_hull(ax, xy, color_hull, label, alpha=0.15)

            ee = ee_points[arm].get(reg_name, np.empty((0, 3)))
            if len(ee) > 0:
                ax.scatter(ee[:, 0], ee[:, 1], s=6, c=color_hull, marker="x",
                           alpha=0.6, label=f"{arm[0].upper()} EE targets", zorder=4)

        ax.legend(loc="upper left", fontsize=6)

    plt.tight_layout()
    out_path = os.path.join(RESULTS_DIR, "per_region_swept_volumes.png")
    plt.savefig(out_path, dpi=200, bbox_inches="tight")
    print(f"Saved per‑region plot to {out_path}")
    plt.close(fig)



def _draw_vehicle(ax):
    cfg = PLOT_CONFIG
    rect = patches.Rectangle(
        (cfg["body_x_min"], cfg["body_y_min"]),
        cfg["body_x_max"] - cfg["body_x_min"],
        cfg["body_y_max"] - cfg["body_y_min"],
        linewidth=2, edgecolor="gray", facecolor="lightgray",
        alpha=0.25, linestyle="--", label="Vehicle body",
    )
    ax.add_patch(rect)


def _draw_planning_regions(ax, alpha_edge=0.6):
    for r in PLANNING_REGIONS:
        border = patches.Rectangle(
            (r["cx"] - r["w"] / 2, r["cy"] - r["h"] / 2),
            r["w"], r["h"],
            linewidth=1.2, edgecolor="black", facecolor="none",
            alpha=alpha_edge, linestyle="--", zorder=3,
        )
        ax.add_patch(border)
        ax.text(
            r["cx"], r["cy"],
            f'{r["name"]}\n({r["arm"]})',
            ha="center", va="center",
            fontsize=6, color="black", fontweight="bold", zorder=4,
        )


def _setup_ax(ax, title, T_left, T_right):
    _draw_vehicle(ax)
    _draw_planning_regions(ax)
    ax.set_title(title, fontsize=10)
    ax.set_xlabel("x (m)")
    ax.set_ylabel("y (m)")
    ax.set_aspect("equal")
    ax.grid(True, alpha=0.3)
    ax.scatter(T_left[0, 3], T_left[1, 3], c="#819CC4", marker="*", s=180,
               label="Left arm base", zorder=5)
    ax.scatter(T_right[0, 3], T_right[1, 3], c="#8CC19A", marker="*", s=180,
               label="Right arm base", zorder=5)


def _draw_hull(ax, pts_2d, color, label, alpha=0.25, linestyle="-"):
    """Draw a filled convex hull for a set of 2‑D points."""
    if len(pts_2d) < 3:
        return
    try:
        hull = ConvexHull(pts_2d)
    except Exception:
        return
    verts = pts_2d[hull.vertices]
    poly = plt.Polygon(verts, closed=True, facecolor=color,
                       edgecolor=color, alpha=alpha, linewidth=1.5,
                       linestyle=linestyle, label=label, zorder=2)
    ax.add_patch(poly)



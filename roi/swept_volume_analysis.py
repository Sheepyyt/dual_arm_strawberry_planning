"""
Swept‑volume analysis for dual‑arm strawberry‑picking robot.

Functionality
=============
1. Forward Kinematics (FK): given an IK joint solution ``q`` and the arm base
   transform, compute the vehicle‑frame positions of **every link origin** along
   the kinematic chain (base_link → link1 → … → link7 → ee_link).
2. Swept‑volume construction: for every reachable target in the ROI table, use
   the *best* IK solution to compute all link positions, then collect them by
   arm and by target region.
3. Safety‑boundary search: find the x‑boundary inside the interference zones
   (B2 / B5) such that, when the *left* end‑effector works only in the
   left‑only zone and the *right* end‑effector works only within the sub‑region
   of B2/B5 beyond that boundary, their link swept volumes are guaranteed
   disjoint — and vice versa.
4. Visualization: multi‑panel plot showing
   (a) per‑arm link swept volumes,
   (b) combined dual‑arm swept volumes with overlap highlighted,
   (c) safety‑boundary overlay.

Usage
-----
    cd roi
    python swept_volume_analysis.py

The script loads the pre‑built ``roi_table.pkl`` (generated by
``build_roi_table.py``) and the URDF, then produces the analysis images
in ``roi/results/``.
"""


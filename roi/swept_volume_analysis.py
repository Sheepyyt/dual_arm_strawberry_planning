# =========================================================
# URDF kinematic‑chain parser
# =========================================================
def parse_arm_chain(urdf_path: str, arm_prefix: str):
    """
    Parse the kinematic chain for one arm from the URDF.

    Parameters
    ----------
    urdf_path : str
        Path to the URDF file.
    arm_prefix : str
        ``"left_arm"`` or ``"right_arm"``.

    Returns
    -------
    chain : list[dict]
        Ordered list of joint descriptions from base_link to ee_link.
        Each dict contains:
        ``name``, ``type`` (``"prismatic"``/``"revolute"``/``"fixed"``),
        ``xyz``, ``rpy``, ``axis``, ``lower``, ``upper``, ``child``.
    """
    tree = ET.parse(urdf_path)
    root = tree.getroot()

    # Build lookup: parent_link → [(joint_elem, child_link)]
    parent_map: dict[str, list] = {}
    for joint in root.findall("joint"):
        parent_link = joint.find("parent").get("link")
        child_link = joint.find("child").get("link")
        parent_map.setdefault(parent_link, []).append((joint, child_link))

    chain = []
    # Start from the arm's base link (naming convention: "{arm_prefix}_base_link")
    current_link = f"{arm_prefix}_base_link"
    if current_link not in {l.get("name") for l in root.findall("link")}:
        raise ValueError(
            f"Base link '{current_link}' not found in URDF. "
            f"Available links: {[l.get('name') for l in root.findall('link')]}"
        )
    while True:
        children = parent_map.get(current_link, [])
        # Filter to same arm
        arm_children = [
            (j, c) for j, c in children if c.startswith(arm_prefix)
        ]
        if not arm_children:
            break
        joint_elem, child_link = arm_children[0]
        origin = joint_elem.find("origin")
        if origin is not None:
            xyz = [float(v) for v in origin.get("xyz", "0 0 0").split()]
            rpy = [float(v) for v in origin.get("rpy", "0 0 0").split()]
        else:
            xyz = [0.0, 0.0, 0.0]
            rpy = [0.0, 0.0, 0.0]

        axis_elem = joint_elem.find("axis")
        axis = (
            [float(v) for v in axis_elem.get("xyz", "0 0 0").split()]
            if axis_elem is not None
            else [0.0, 0.0, 0.0]
        )
        limit = joint_elem.find("limit")
        lower = float(limit.get("lower", "0")) if limit is not None else 0.0
        upper = float(limit.get("upper", "0")) if limit is not None else 0.0

        chain.append({
            "name": joint_elem.get("name"),
            "type": joint_elem.get("type"),
            "xyz": np.asarray(xyz, dtype=float),
            "rpy": np.asarray(rpy, dtype=float),
            "axis": np.asarray(axis, dtype=float),
            "lower": lower,
            "upper": upper,
            "child": child_link,
        })
        current_link = child_link
    return chain


def _joint_transform(joint_desc: dict, q_val: float) -> np.ndarray:
    """
    Compute the 4×4 homogeneous transform for a single joint at joint
    value ``q_val``.

    For a **prismatic** joint the translation is the static origin xyz plus
    ``q_val`` along the joint axis.  For a **revolute** joint the rotation
    is the static origin rotation composed with ``q_val`` about the joint
    axis.  A **fixed** joint simply returns the static origin.
    """
    T_origin = xyzrpy_to_T(joint_desc["xyz"], joint_desc["rpy"])
    jtype = joint_desc["type"]
    if jtype == "fixed":
        return T_origin

    if jtype == "prismatic":
        T_motion = np.eye(4)
        T_motion[:3, 3] = joint_desc["axis"] * q_val
        return T_origin @ T_motion

    if jtype == "revolute":
        ax = joint_desc["axis"]
        # Rodrigues formula for rotation about an arbitrary unit axis.
        # The current URDF uses axes of the form (0,0,±1), but this
        # implementation handles general unit axes correctly.
        angle = q_val
        ax_norm = np.linalg.norm(ax)
        if ax_norm < 1e-12:
            return T_origin
        ax = ax / ax_norm
        K = np.array([
            [0, -ax[2], ax[1]],
            [ax[2], 0, -ax[0]],
            [-ax[1], ax[0], 0],
        ])
        R_motion = np.eye(3) + np.sin(angle) * K + (1 - np.cos(angle)) * (K @ K)
        T_motion = np.eye(4)
        T_motion[:3, :3] = R_motion
        return T_origin @ T_motion

    # Fallback
    return T_origin


# =========================================================
# Forward kinematics – all link origins
# =========================================================
def compute_fk_all_links(
    chain: list,
    q: np.ndarray,
    T_vehicle_from_arm: np.ndarray,
) -> dict:
    """
    Compute the vehicle‑frame positions of every link origin given joint
    values ``q``.

    Parameters
    ----------
    chain : list[dict]
        Kinematic chain as returned by :func:`parse_arm_chain`.
    q : ndarray, shape (n_actuated,)
        Joint values for the actuated (non‑fixed) joints, in chain order.
    T_vehicle_from_arm : ndarray, shape (4,4)
        Transform from arm base_link frame to vehicle frame.

    Returns
    -------
    link_positions : dict[str, ndarray]
        ``{child_link_name: vehicle_xyz}`` for every link in the chain,
        including ``base_link`` (at the arm origin).
    """
    T_accum = T_vehicle_from_arm.copy()
    positions = {}

    # Record arm base position
    positions["base_link"] = T_accum[:3, 3].copy()

    q_idx = 0
    for jd in chain:
        if jd["type"] == "fixed":
            T_joint = _joint_transform(jd, 0.0)
        else:
            T_joint = _joint_transform(jd, float(q[q_idx]))
            q_idx += 1
        T_accum = T_accum @ T_joint
        positions[jd["child"]] = T_accum[:3, 3].copy()

    return positions


# =========================================================
# Classify a vehicle‑frame target point into B1‑B6 regions
# =========================================================
def classify_point_region(x: float, y: float) -> str | None:
    """Return 'B1'..'B6' if the point falls inside one of the planning
    regions, otherwise ``None``."""
    for r in PLANNING_REGIONS:
        x_lo = r["cx"] - r["w"] / 2
        x_hi = r["cx"] + r["w"] / 2
        y_lo = r["cy"] - r["h"] / 2
        y_hi = r["cy"] + r["h"] / 2
        if x_lo <= x <= x_hi and y_lo <= y <= y_hi:
            return r["name"]
    return None


# =========================================================
# Compute swept volumes from the ROI table
# =========================================================
def compute_swept_volumes(roi_payload: dict, T_left, T_right, urdf_path: str):
    """
    For every reachable grid point in the ROI table, compute all link
    positions using the *best* IK solution, then group by arm and by
    region.

    Returns
    -------
    swept : dict
        ``swept["left"]``  → dict  region_name → ndarray (N, 3)
        ``swept["right"]`` → dict  region_name → ndarray (N, 3)
    ee_points : dict
        ``ee_points["left"]``  → dict  region_name → ndarray (M, 3)
        ``ee_points["right"]`` → dict  region_name → ndarray (M, 3)
    """
    # Both arms share identical kinematic structure (same joint types,
    # DH parameters, and link lengths) – only the base transform differs.
    # The ROI builder (build_roi_table.py) already exploits this symmetry
    # by using a single left_arm IK chain for both arms, transforming
    # targets into each arm's local frame.  We reuse the same chain here
    # for FK; the arm‑specific base transform (T_left / T_right) converts
    # the result back to the vehicle frame.
    chain = parse_arm_chain(urdf_path, "left_arm")

    roi = roi_payload["data"]

    swept = {"left": {}, "right": {}}
    ee_points = {"left": {}, "right": {}}

    for key, item in roi.items():
        x_v, y_v, z_v = item["vehicle_xyz"]
        region = classify_point_region(x_v, y_v)

        for arm in ("left", "right"):
            entry = item[arm]
            q_best = entry.get("best_solution")
            if q_best is None:
                continue
            q_best = np.asarray(q_best, dtype=float)
            T_base = T_left if arm == "left" else T_right
            link_pos = compute_fk_all_links(chain, q_best, T_base)

            region_key = region if region is not None else "outside"
            swept[arm].setdefault(region_key, [])
            ee_points[arm].setdefault(region_key, [])

            for link_name, pos in link_pos.items():
                swept[arm][region_key].append(pos)

            # Record end‑effector position separately
            ee_pos = np.array([x_v, y_v, z_v], dtype=float)
            ee_points[arm][region_key].append(ee_pos)

    # Convert lists to arrays
    for arm in ("left", "right"):
        for reg in list(swept[arm].keys()):
            swept[arm][reg] = np.asarray(swept[arm][reg], dtype=float)
        for reg in list(ee_points[arm].keys()):
            ee_points[arm][reg] = np.asarray(ee_points[arm][reg], dtype=float)

    return swept, ee_points


# =========================================================
# Overlap detection helpers (XY projection)
# =========================================================
def points_to_xy(pts: np.ndarray) -> np.ndarray:
    """Project (N,3) or (N,2) points to (N,2) XY."""
    return pts[:, :2]


def convex_hull_polygon(pts_2d: np.ndarray):
    """Return the ordered vertices of the convex hull of 2‑D points."""
    if len(pts_2d) < 3:
        return pts_2d
    try:
        hull = ConvexHull(pts_2d)
        return pts_2d[hull.vertices]
    except Exception:
        return pts_2d


def polygons_overlap(poly_a: np.ndarray, poly_b: np.ndarray) -> bool:
    """
    Check if two convex polygons (given as ordered vertex arrays)
    overlap using the Separating Axis Theorem (SAT).
    """
    def _edges(poly):
        edges = []
        n = len(poly)
        for i in range(n):
            edges.append(poly[(i + 1) % n] - poly[i])
        return edges

    def _project(poly, axis):
        dots = poly @ axis
        return dots.min(), dots.max()

    if len(poly_a) < 2 or len(poly_b) < 2:
        return False

    for poly in (poly_a, poly_b):
        for edge in _edges(poly):
            normal = np.array([-edge[1], edge[0]])
            norm = np.linalg.norm(normal)
            if norm < 1e-12:
                continue
            normal /= norm
            min_a, max_a = _project(poly_a, normal)
            min_b, max_b = _project(poly_b, normal)
            if max_a < min_b or max_b < min_a:
                return False
    return True


def compute_overlap_points(pts_a_2d: np.ndarray, pts_b_2d: np.ndarray,
                           grid_step: float = 0.005) -> np.ndarray:
    """
    Return an (M, 2) array of grid points that are inside **both** convex
    hulls (approximation of intersection area for visualization).
    """
    if len(pts_a_2d) < 3 or len(pts_b_2d) < 3:
        return np.empty((0, 2))

    try:
        hull_a = ConvexHull(pts_a_2d)
        hull_b = ConvexHull(pts_b_2d)
    except Exception:
        return np.empty((0, 2))

    # Bounding box of intersection
    verts_a = pts_a_2d[hull_a.vertices]
    verts_b = pts_b_2d[hull_b.vertices]
    x_lo = max(verts_a[:, 0].min(), verts_b[:, 0].min())
    x_hi = min(verts_a[:, 0].max(), verts_b[:, 0].max())
    y_lo = max(verts_a[:, 1].min(), verts_b[:, 1].min())
    y_hi = min(verts_a[:, 1].max(), verts_b[:, 1].max())

    if x_lo >= x_hi or y_lo >= y_hi:
        return np.empty((0, 2))

    xs = np.arange(x_lo, x_hi + grid_step * 0.5, grid_step)
    ys = np.arange(y_lo, y_hi + grid_step * 0.5, grid_step)
    grid = np.array(np.meshgrid(xs, ys)).T.reshape(-1, 2)

    def _in_hull(pts, hull):
        try:
            d = Delaunay(pts[hull.vertices])
            return d.find_simplex(grid) >= 0
        except Exception:
            return np.zeros(len(grid), dtype=bool)

    mask = _in_hull(pts_a_2d, hull_a) & _in_hull(pts_b_2d, hull_b)
    return grid[mask]


# =========================================================
# Safety boundary search
# =========================================================
def _search_one_scenario(
    fixed_arm: str,
    fixed_exclusive: str,
    moving_arm: str,
    interf_region: str,
    ix_lo: float,
    ix_hi: float,
    roi_data: dict,
    T_left,
    T_right,
    chain: list,
    buffer: float,
    step: float,
):
    """
    Core boundary search for one scenario direction.

    *fixed_arm* works exclusively in *fixed_exclusive*.
    *moving_arm* works in *interf_region*, restricted by a boundary.

    For the *left* fixed arm (Scenario A), the moving arm is the right arm
    and we restrict ``x ≥ boundary``, scanning from right→left.
    For the *right* fixed arm (Scenario B), the moving arm is the left arm
    and we restrict ``x ≤ boundary``, scanning from left→right.

    Returns ``(boundary_x, info_dict)``.
    """
    is_scenario_A = (fixed_arm == "left")  # left exclusive, right moving

    def _gather_link_points(arm, ee_targets):
        pts = []
        T_base = T_left if arm == "left" else T_right
        for key, item in roi_data.items():
            entry = item[arm]
            q_best = entry.get("best_solution")
            if q_best is None:
                continue
            x_v, y_v, _ = item["vehicle_xyz"]
            if (x_v, y_v) not in ee_targets:
                continue
            q_best = np.asarray(q_best, dtype=float)
            link_pos = compute_fk_all_links(chain, q_best, T_base)
            for _, pos in link_pos.items():
                pts.append(pos[:2])
        return np.asarray(pts, dtype=float) if pts else np.empty((0, 2))

    def _ee_targets(arm, regions, x_bound=None, bound_side=None):
        targets = set()
        for key, item in roi_data.items():
            if item[arm].get("best_solution") is None:
                continue
            x_v, y_v, _ = item["vehicle_xyz"]
            reg = classify_point_region(x_v, y_v)
            if reg not in regions:
                continue
            if x_bound is not None:
                if bound_side == "left" and x_v > x_bound + 1e-9:
                    continue
                if bound_side == "right" and x_v < x_bound - 1e-9:
                    continue
            targets.add((x_v, y_v))
        return targets

    def _check(fixed_pts, moving_pts, buf):
        if len(fixed_pts) < 3 or len(moving_pts) < 3:
            return False
        ha = convex_hull_polygon(fixed_pts)
        hb = convex_hull_polygon(moving_pts)
        if len(ha) < 3 or len(hb) < 3:
            return False
        if buf > 0:
            ha = _inflate_polygon(ha, buf)
            hb = _inflate_polygon(hb, buf)
        return polygons_overlap(ha, hb)

    # Fixed arm body (independent of boundary)
    fixed_targets = _ee_targets(fixed_arm, {fixed_exclusive})
    fixed_link_pts = _gather_link_points(fixed_arm, fixed_targets)

    x_candidates = np.arange(ix_lo, ix_hi + step * 0.5, step)
    if is_scenario_A:
        x_iter = reversed(x_candidates)
        bound_side = "right"
    else:
        x_iter = iter(x_candidates)
        bound_side = "left"

    best_bx = None
    best_info = None

    for bx in x_iter:
        moving_targets = _ee_targets(
            moving_arm, {interf_region}, x_bound=bx, bound_side=bound_side,
        )
        if not moving_targets:
            best_bx = bx
            constraint = f"x≥{bx:.2f}" if is_scenario_A else f"x≤{bx:.2f}"
            best_info = {
                "boundary_x": bx,
                "fixed_link_pts": fixed_link_pts,
                "moving_link_pts": np.empty((0, 2)),
                "overlap": False,
                "constraint": constraint,
            }
            continue

        moving_link_pts = _gather_link_points(moving_arm, moving_targets)
        overlap = _check(fixed_link_pts, moving_link_pts, buffer)

        if not overlap:
            constraint = f"x≥{bx:.2f}" if is_scenario_A else f"x≤{bx:.2f}"
            best_bx = bx
            best_info = {
                "boundary_x": bx,
                "fixed_link_pts": fixed_link_pts,
                "moving_link_pts": moving_link_pts,
                "overlap": False,
                "constraint": constraint,
            }
        else:
            break

    if best_info is None:
        best_info = {
            "boundary_x": None,
            "fixed_link_pts": fixed_link_pts,
            "moving_link_pts": np.empty((0, 2)),
            "overlap": True,
            "constraint": "none",
        }

    return best_bx, best_info


def find_safety_boundary(
    swept: dict,
    ee_points: dict,
    T_left,
    T_right,
    chain: list,
    roi_payload: dict,
    side: str,
    buffer: float = 0.03,
    step: float = 0.01,
):
    """
    For a given *side* (``"upper"`` = B1/B2/B3 fruit band or ``"lower"``
    = B4/B5/B6), find the x‑boundary inside the interference zone (B2 or
    B5) for two scenarios, each at two buffer levels (0 cm and the
    specified buffer):

    **Scenario A** ("left in exclusive, right in interference"):
      Left arm EE works exclusively in B1 (or B4).  Right arm EE works
      in the interference zone (B2 or B5) restricted to ``x ≥ boundary``.

    **Scenario B** ("right in exclusive, left in interference"):
      Right arm EE works exclusively in B3 (or B6).  Left arm EE works
      in the interference zone restricted to ``x ≤ boundary``.

    Returns
    -------
    results : dict  with keys ``"scenario_A"`` and ``"scenario_B"``.
        Each value is a dict with ``"buffered"`` and ``"raw"`` sub‑dicts,
        each containing ``(boundary_x, info_dict)``.
    """
    if side == "upper":
        interf_region = "B2"
        left_exclusive = "B1"
        right_exclusive = "B3"
    else:
        interf_region = "B5"
        left_exclusive = "B4"
        right_exclusive = "B6"

    for r in PLANNING_REGIONS:
        if r["name"] == interf_region:
            ix_lo = r["cx"] - r["w"] / 2
            ix_hi = r["cx"] + r["w"] / 2
            break

    roi_data = roi_payload["data"]
    common = dict(
        roi_data=roi_data, T_left=T_left, T_right=T_right,
        chain=chain, ix_lo=ix_lo, ix_hi=ix_hi, step=step,
    )

    # ---- Scenario A (left exclusive, right in interf) ----
    bnd_A_buf, info_A_buf = _search_one_scenario(
        fixed_arm="left", fixed_exclusive=left_exclusive,
        moving_arm="right", interf_region=interf_region,
        buffer=buffer, **common,
    )
    bnd_A_raw, info_A_raw = _search_one_scenario(
        fixed_arm="left", fixed_exclusive=left_exclusive,
        moving_arm="right", interf_region=interf_region,
        buffer=0.0, **common,
    )

    info_A_buf["description"] = (
        f"L‑EE in {left_exclusive}; R‑EE in "
        f"{interf_region} ({info_A_buf['constraint']}), "
        f"buf={buffer*100:.0f}cm"
    )
    info_A_raw["description"] = (
        f"L‑EE in {left_exclusive}; R‑EE in "
        f"{interf_region} ({info_A_raw['constraint']}), "
        f"buf=0cm"
    )

    # ---- Scenario B (right exclusive, left in interf) ----
    bnd_B_buf, info_B_buf = _search_one_scenario(
        fixed_arm="right", fixed_exclusive=right_exclusive,
        moving_arm="left", interf_region=interf_region,
        buffer=buffer, **common,
    )
    bnd_B_raw, info_B_raw = _search_one_scenario(
        fixed_arm="right", fixed_exclusive=right_exclusive,
        moving_arm="left", interf_region=interf_region,
        buffer=0.0, **common,
    )

    info_B_buf["description"] = (
        f"R‑EE in {right_exclusive}; L‑EE in "
        f"{interf_region} ({info_B_buf['constraint']}), "
        f"buf={buffer*100:.0f}cm"
    )
    info_B_raw["description"] = (
        f"R‑EE in {right_exclusive}; L‑EE in "
        f"{interf_region} ({info_B_raw['constraint']}), "
        f"buf=0cm"
    )

    return {
        "scenario_A": {
            "buffered": (bnd_A_buf, info_A_buf),
            "raw": (bnd_A_raw, info_A_raw),
        },
        "scenario_B": {
            "buffered": (bnd_B_buf, info_B_buf),
            "raw": (bnd_B_raw, info_B_raw),
        },
    }


def _inflate_polygon(verts: np.ndarray, d: float) -> np.ndarray:
    """Inflate a convex polygon outward by distance ``d``.

    Uses a simple radial expansion from the centroid.  This is an
    approximation that works well for roughly convex, compact shapes but
    does **not** produce a uniformly offset polygon (Minkowski sum with a
    disk).  For the safety‑boundary analysis the approximation is
    conservative enough because the convex hulls are already a superset
    of the true link volumes.
    """
    center = verts.mean(axis=0)
    directions = verts - center
    norms = np.linalg.norm(directions, axis=1, keepdims=True)
    norms = np.maximum(norms, 1e-12)
    return verts + d * directions / norms



    plt.tight_layout()
    out_path = os.path.join(RESULTS_DIR, "swept_volume_analysis.png")
    os.makedirs(RESULTS_DIR, exist_ok=True)
    plt.savefig(out_path, dpi=200, bbox_inches="tight")

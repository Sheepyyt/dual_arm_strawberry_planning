def main():
    urdf_path = CONFIG["urdf_path"]
    roi_file = CONFIG["roi_table_file"]

    if not os.path.exists(roi_file):
        print(f"Error: ROI table not found at {roi_file}. Run build_roi_table.py first.")
        return

    print("Loading ROI table …")
    with open(roi_file, "rb") as f:
        roi_payload = pickle.load(f)

    T_left, T_right = load_base_transforms_from_urdf(
        urdf_path, CONFIG["left_base_joint"], CONFIG["right_base_joint"],
    )
    print(f"Left base:  {T_left[:3, 3]}")
    print(f"Right base: {T_right[:3, 3]}")

    # ------------------------------------------------------------------
    print("Computing swept volumes …")
    swept, ee_points = compute_swept_volumes(roi_payload, T_left, T_right, urdf_path)

    for arm in ("left", "right"):
        total = sum(len(v) for v in swept[arm].values())
        print(f"  {arm} arm: {total} link‑position samples across "
              f"{len(swept[arm])} regions")

    # ------------------------------------------------------------------
    print("Searching safety boundaries …")
    chain = parse_arm_chain(urdf_path, "left_arm")

    results_upper = find_safety_boundary(
        swept, ee_points, T_left, T_right, chain, roi_payload,
        side="upper",
        buffer=PLOT_CONFIG["link_safety_buffer"],
        step=PLOT_CONFIG["boundary_search_step"],
    )
    results_lower = find_safety_boundary(
        swept, ee_points, T_left, T_right, chain, roi_payload,
        side="lower",
        buffer=PLOT_CONFIG["link_safety_buffer"],
        step=PLOT_CONFIG["boundary_search_step"],
    )

    for label, results in [("Upper", results_upper), ("Lower", results_lower)]:
        for sc in ("scenario_A", "scenario_B"):
            for lvl in ("raw", "buffered"):
                bnd, info = results[sc][lvl]
                desc = info.get("description", "")
                tag = f"{label} {sc} ({lvl})"
                if bnd is not None:
                    print(f"  {tag}: x = {bnd:+.3f} m  [{desc}]")
                else:
                    print(f"  {tag}: NO safe boundary  [{desc}]")

    # ------------------------------------------------------------------
    print("Generating plots …")
    plot_swept_volume_analysis(
        swept, ee_points, T_left, T_right,
        results_upper, results_lower,
    )
    plot_per_region_swept_volumes(swept, ee_points, T_left, T_right)

    print("Done.")


if __name__ == "__main__":
    main()
